export function formatPolicyDate(iso: string): string {
  return new Intl.DateTimeFormat("ar-u-ca-gregory-nu-arab", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" }).format(
    new Date(`${iso}T00:00:00Z`),
  );
}

